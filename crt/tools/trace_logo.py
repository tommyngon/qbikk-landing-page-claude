"""Trace the supplied QBIKK raster logo to a vector SVG (potracer = pure-python potrace).
Usage: python3 trace_logo.py <logo.webp|png> <out.svg>
"""
import sys
import numpy as np
from PIL import Image
import potrace

src, out = sys.argv[1], sys.argv[2]
im = Image.open(src).convert("L")
w, h = im.size
a = np.array(im) < 128          # True = ink
bm = potrace.Bitmap(~a)   # potracer traces the False pixels; ink must be the False side
plist = bm.trace(turdsize=20, turnpolicy=potrace.POTRACE_TURNPOLICY_MINORITY,
                 alphamax=1.0, opticurve=True, opttolerance=0.2)
parts = []
for curve in plist:
    s = curve.start_point
    d = [f"M{s.x:.2f},{s.y:.2f}"]
    for seg in curve.segments:
        if seg.is_corner:
            d.append(f"L{seg.c.x:.2f},{seg.c.y:.2f}L{seg.end_point.x:.2f},{seg.end_point.y:.2f}")
        else:
            d.append(f"C{seg.c1.x:.2f},{seg.c1.y:.2f} {seg.c2.x:.2f},{seg.c2.y:.2f} {seg.end_point.x:.2f},{seg.end_point.y:.2f}")
    d.append("Z")
    parts.append("".join(d))
svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}">'
       f'<path fill="currentColor" fill-rule="evenodd" d="{" ".join(parts)}"/></svg>\n')
open(out, "w").write(svg)
print(f"traced {len(plist)} curves, {w}x{h} -> {out}")

# Also emit shared/logo.js (global QCRT.LOGO) so the demos need no fetch/parse.
ys, xs = np.where(a)
ink = dict(x=int(xs.min()), y=int(ys.min()), w=int(xs.max() - xs.min() + 1), h=int(ys.max() - ys.min() + 1))
d_all = " ".join(parts)
js = ("/* GENERATED by tools/trace_logo.py from the supplied QBIKK logo. Do not edit. */\n"
      "(function (g) { g.QCRT = g.QCRT || {}; g.QCRT.LOGO = "
      + __import__("json").dumps(dict(viewBox=[0, 0, w, h], ink=ink, d=d_all)) + "; })(typeof self !== 'undefined' ? self : this);\n")
open(out.rsplit("/", 1)[0] + "/logo.js", "w").write(js)
print("ink box", ink)
